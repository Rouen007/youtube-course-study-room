#!/usr/bin/env python3
"""
Study Room Data Pack Compiler & Version Stamper
Part of YouTube Course Study Room Framework
Created by Xiao Ang

Compiles course metadata, transcripts, keyframes, and distillation models
into standalone JavaScript data packages and stamps version.json / version.js
for the GitHub Red-Dot Sync Engine.

Usage:
    python3 build_study_room.py --project-dir ./study-room
"""

import argparse
import datetime
import json
import os
import subprocess
import sys


def get_git_info(target_dir):
    """Retrieve current commit SHA and status."""
    try:
        sha = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=target_dir, stderr=subprocess.DEVNULL).decode('utf-8').strip()
    except Exception:
        sha = "local-dev"
    return sha


def stamp_version(target_dir):
    """Write version.json and version.js with ISO-8601 UTC timestamp and commit SHA."""
    now_utc = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    commit_sha = get_git_info(target_dir)

    version_data = {
        "version": "1.0.0",
        "updatedAt": now_utc,
        "commitSha": commit_sha,
        "curatedBy": "Created by Xiao Ang",
        "framework": "YouTube Course Study Room"
    }

    # Write version.json (used by remote GitHub sync check)
    vjson_path = os.path.join(target_dir, "version.json")
    with open(vjson_path, 'w', encoding='utf-8') as f:
        json.dump(version_data, f, indent=2, ensure_ascii=False)

    # Write version.js (for browser direct inclusion)
    vjs_path = os.path.join(target_dir, "version.js")
    with open(vjs_path, 'w', encoding='utf-8') as f:
        f.write(f"// Auto-generated by build_study_room.py - Created by Xiao Ang\n")
        f.write(f"window.APP_VERSION = {json.dumps(version_data, indent=2, ensure_ascii=False)};\n")

    print(f"[✓] Stamped {vjson_path} and {vjs_path} (Timestamp: {now_utc}, Commit: {commit_sha[:7]})")


def main():
    parser = argparse.ArgumentParser(description="Study Room Data Pack Compiler (Created by Xiao Ang)")
    parser.add_argument("--project-dir", default="./study-room", help="Path to study-room web directory")
    args = parser.parse_args()

    target_dir = os.path.abspath(args.project_dir)
    if not os.path.exists(target_dir):
        print(f"[!] Target directory does not exist: {target_dir}", file=sys.stderr)
        sys.exit(1)

    print(f"[*] Building study room at: {target_dir}")
    stamp_version(target_dir)

    # Validate essential files
    required_files = ["index.html", "style.css", "app.js", "library-data.js", "distill-data.js"]
    missing = [f for f in required_files if not os.path.exists(os.path.join(target_dir, f))]
    if missing:
        print(f"[!] Warning: Missing expected files: {missing}")
    else:
        print("[✓] All core frontend assets verified.")

    print("[🎉] Build completed successfully. Created by Xiao Ang.")


if __name__ == "__main__":
    main()
